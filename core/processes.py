@dataclass(frozen=True)
class RuntimeStatus:
    state: str = "stopped"
    message: str = "已停止"
    pid: Optional[int] = None
    log_path: str = ""


def _safe_text(text: str, sensitive: tuple[str, ...] = ()) -> str:
    # Autogenerated GUI login URLs can contain credentials even in fragments.
    def clean_url(match: re.Match) -> str:
        value = match.group(0)
        try:
            parts = urllib.parse.urlsplit(value)
            host = parts.hostname or "localhost"
            if parts.port:
                host += f":{parts.port}"
            return urllib.parse.urlunsplit((parts.scheme, host, parts.path, "", ""))
        except ValueError:
            return "[redacted URL]"
    text = re.sub(r"https?://[^\s<>\"']+", clean_url, text)
    text = re.sub(r"(?i)((?:--)?(?:rc-)?(?:pass(?:word)?|user(?:name)?|login_token|token|secret|authorization)\s*(?:=|:)\s*)(?:\"[^\"]*\"|'[^']*'|[^\s,;]+)",
                  r"\1[redacted]", text)
    for value in sorted(set(sensitive), key=len, reverse=True):
        # 过短的凭据整词替换会毁掉诊断文本；短值交给上面的正则处理。
        if len(value) >= 4:
            text = text.replace(value, "[redacted]")
            encoded = urllib.parse.quote(value, safe="")
            if encoded != value:
                text = text.replace(encoded, "[redacted]")
            form_encoded = urllib.parse.quote_plus(value, safe="")
            if form_encoded != value:
                text = text.replace(form_encoded, "[redacted]")
    return text


def _port_free(port: int) -> bool:
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            if hasattr(socket, "SO_EXCLUSIVEADDRUSE"):
                sock.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
            sock.bind(("127.0.0.1", port))
        return True
    except OSError:
        return False


def _available_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def _http(url: str, user: str = "", password: str = "", *, post: bool = False,
          timeout: float = 0.7) -> bytes:
    request = urllib.request.Request(url, data=b"{}" if post else None)
    if post:
        request.add_header("Content-Type", "application/json")
    if user or password:
        token = base64.b64encode(f"{user}:{password}".encode("utf-8")).decode("ascii")
        request.add_header("Authorization", "Basic " + token)
    # Ignore system proxy settings for owned loopback endpoints.
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    with opener.open(request, timeout=timeout) as response:
        return response.read(65536)


def _child_environment() -> dict[str, str]:
    env = os.environ.copy()
    for key in tuple(env):
        if key.startswith("RCLONE_RC_") or key in {
            "RCLONE_USER", "RCLONE_PASS", "RCLONE_NO_AUTH", "RCLONE_LOG_FILE",
            "RCLONE_DUMP", "RCLONE_DUMP_BODIES", "RCLONE_DUMP_HEADERS",
            "RCLONE_CPUPROFILE", "RCLONE_MEMPROFILE", "RCLONE_SYSLOG",
            "RCLONE_LOG_SYSTEMD", "RCLONE_WINDOWS_EVENT_LOG_LEVEL",
        }:
            env.pop(key, None)
    temporary = app_data_dir() / "temp"
    temporary.mkdir(parents=True, exist_ok=True)
    env.update(RCLONE_TEMP_DIR=str(temporary), TMP=str(temporary), TEMP=str(temporary))
    return env


class BaseProcess:
    START_TIMEOUT = 30.0
    STOP_TIMEOUT = 8.0

    def __init__(self, cfg: AppConfig, log_name: str, cancel: threading.Event):
        self.cfg = copy.deepcopy(cfg)
        self.exe = cfg.rclone_path
        self.proc: Optional[subprocess.Popen] = None
        self.cancel = cancel
        self.log_name = log_name
        self._log_file: Optional[Path] = None
        self._state = "stopped"
        self._message = "已停止"
        self._lock = threading.RLock()
        self._operation = threading.Lock()
        self._tail: deque[str] = deque(maxlen=8)
        self._reader: Optional[threading.Thread] = None
        self._log_error = ""
        self._secrets: tuple[str, ...] = (cfg.gui_user, cfg.gui_pass)
        self._rc_url = ""
        self._rc_user = ""
        self._rc_pass = ""

    def running(self) -> bool:
        with self._lock:
            return self.proc is not None and self.proc.poll() is None

    def owned(self) -> bool:
        return self.running()

    def _status(self, state: Optional[str] = None, message: Optional[str] = None) -> RuntimeStatus:
        with self._lock:
            if state is not None:
                self._state = state
            if message is not None:
                self._message = _safe_text(message, self._secrets)
            pid = self.proc.pid if self.proc is not None and self.proc.poll() is None else None
            return RuntimeStatus(self._state, self._message, pid,
                                 str(self._log_file) if self._log_file is not None else "")

    def status(self) -> RuntimeStatus:
        with self._lock:
            if self.proc is not None and self.proc.poll() is not None and self._state in {"starting", "ready"}:
                self._state = "failed"
                self._message = self._failure_message(f"rclone 已意外退出（代码 {self.proc.returncode}）。请查看日志和配置后重试。")
            return self._status()

    def _failure_message(self, message: str) -> str:
        with self._lock:
            detail = " | ".join(self._tail)
        return _safe_text(message + (" " + detail if detail else ""), self._secrets)

    def _drain_output(self, process: subprocess.Popen, stream) -> None:
        try:
            for line in process.stdout:
                safe = _safe_text(line.decode("utf-8", errors="replace"), self._secrets)
                try:
                    stream.write(safe)
                    stream.flush()
                except OSError:
                    with self._lock:
                        self._log_error = "日志写入失败；请检查应用数据目录权限和磁盘空间。"
                    # Keep draining to avoid deadlocking a child on a full pipe.
                with self._lock:
                    self._tail.append(safe.strip()[-1600:])
        finally:
            process.stdout.close()
            stream.close()

    def _spawn(self, args: list[str], env: dict[str, str]) -> None:
        self._log_file = logs_dir() / f"{self.log_name}.log"
        stream = self._log_file.open("w", encoding="utf-8", newline="\n")
        flags = no_window_flag() | getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0)
        try:
            process = subprocess.Popen(args, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                       stdin=subprocess.DEVNULL, creationflags=flags,
                                       shell=False, env=env)
        except BaseException:
            stream.close()
            raise
        with self._lock:
            self.proc = process
            self._tail.clear()
            self._log_error = ""
        self._reader = threading.Thread(target=self._drain_output, args=(process, stream),
                                        daemon=True, name=f"rclone-log-{self.log_name}")
        self._reader.start()

    def _config_args(self) -> list[str]:
        conf = find_rclone_conf(self.cfg.rclone_conf)
        if conf is not None:
            return ["--config", str(conf)]
        if os.environ.get("RCLONE_TRAY_DATA_DIR"):
            # Never let an isolated run silently discover the user's real config.
            return ["--config", str(app_data_dir() / "rclone.conf")]
        return []

    def _preflight(self) -> str:
        if self.cancel.is_set():
            return "启动已取消；应用正在退出。"
        exe = find_rclone(self.cfg.rclone_path)
        if not exe:
            return "rclone 可执行文件不存在；请在设置中选择有效的 rclone.exe。"
        self.exe = exe
        if get_version(exe) is None:
            return "所选程序未返回有效 rclone 版本；请检查文件、执行权限和安全软件。"
        return ""

    def _rc_pid_matches(self) -> bool:
        if not self.running() or not self._rc_url:
            return False
        try:
            value = json.loads(_http(self._rc_url + "core/pid", self._rc_user, self._rc_pass, post=True))
            return isinstance(value, dict) and type(value.get("pid")) is int and value["pid"] == self.proc.pid and self.running()
        except (OSError, ValueError, urllib.error.URLError):
            return False

    def _ready(self) -> bool:
        return self._rc_pid_matches()

    def _wait_ready(self) -> RuntimeStatus:
        deadline = time.monotonic() + self.START_TIMEOUT
        while time.monotonic() < deadline:
            if self.cancel.is_set():
                return self._abort_start("启动已取消。")
            if not self.running():
                if self._reader is not None:
                    self._reader.join(timeout=0.25)
                return self._abort_start(self._failure_message("rclone 启动失败并退出；请检查配置和日志。"))
            if self._log_error:
                return self._abort_start(self._log_error)
            if self._ready() and not self.cancel.is_set() and self.running():
                return self._status("ready", "已就绪")
            self.cancel.wait(0.15)
        return self._abort_start("等待就绪超时；请检查 remote、网络、依赖和日志。")

    def _abort_start(self, message: str) -> RuntimeStatus:
        try:
            result = self._stop_impl()
            if result.state != "stopped":
                message += " 清理未完成：" + result.message
        except (OSError, ConfigError) as exc:
            message += " 清理未完成：" + (str(exc) if isinstance(exc, ConfigError)
                                          else "无法确认卸载或恢复空目录；请重试停止。")
        return self._status("failed", message)

    def _gone(self) -> bool:
        return True

    def _stop_impl(self) -> RuntimeStatus:
        process = self.proc
        self._status("stopping", "正在停止并确认退出")
        if process is not None and process.poll() is None:
            # RC quit lets WinFsp unmount cleanly and VFS release its files.
            try:
                if self._rc_pid_matches():
                    _http(self._rc_url + "core/quit", self._rc_user, self._rc_pass,
                          post=True, timeout=0.7)
                elif os.name != "nt":
                    process.send_signal(signal.SIGTERM)
                else:
                    process.send_signal(getattr(signal, "CTRL_BREAK_EVENT", signal.SIGTERM))
            except (OSError, ValueError, urllib.error.URLError):
                pass
            try:
                process.wait(timeout=self.STOP_TIMEOUT)
            except subprocess.TimeoutExpired:
                try:
                    process.terminate()
                    process.wait(timeout=3)
                except (OSError, subprocess.TimeoutExpired):
                    try:
                        process.kill()
                        process.wait(timeout=3)
                    except (OSError, subprocess.TimeoutExpired):
                        return self._status("failed", "无法停止 rclone；仍保留进程控制权。请关闭占用文件后重试停止。")
        if process is not None and process.poll() is None:
            return self._status("failed", "rclone 仍在运行；请重试停止，不能退出应用。")
        deadline = time.monotonic() + self.STOP_TIMEOUT
        while not self._gone():
            if time.monotonic() >= deadline:
                return self._status("failed", "进程已退出但挂载仍存在；请关闭占用文件并重试停止，勿修改或删除此配置。")
            time.sleep(0.15)
        if self._reader is not None:
            self._reader.join(timeout=1)
        with self._lock:
            self.proc = None
        return self._status("stopped", "已停止并确认退出")

    def stop(self) -> RuntimeStatus:
        with self._operation:
            try:
                return self._stop_impl()
            except (OSError, ConfigError) as exc:
                message = str(exc) if isinstance(exc, ConfigError) else f"停止失败（{type(exc).__name__}）；请检查路径和权限。"
                return self._status("failed", message + " 仍保留控制权，请重试停止。")


class GuiService(BaseProcess):
    GUI_PORT = 5570
    API_PORT = 5572
    HOST = "127.0.0.1"

    def __init__(self, cfg: AppConfig, cancel: threading.Event):
        super().__init__(cfg, "gui", cancel)
        self._base_url = ""
        self._open_url = ""
        self._version: Optional[str] = None

    def _preflight(self) -> str:
        if self.cancel.is_set():
            return "启动已取消；应用正在退出。"
        exe = find_rclone(self.cfg.rclone_path)
        if not exe:
            return "rclone 可执行文件不存在；请在设置中选择有效的 rclone.exe。"
        self.exe = exe
        self._version = get_version(exe)
        if self._version is None:
            return "所选程序未返回有效 rclone 版本；请检查文件和执行权限。"
        if not self.cfg.gui_no_auth and (not self.cfg.gui_user.strip() or not self.cfg.gui_pass):
            return "启用认证必须填写用户名和密码；不会自动使用默认凭据。"
        if ":" in self.cfg.gui_user or any(ch in self.cfg.gui_user for ch in "\r\n"):
            return "认证用户名不能包含冒号或换行。"
        ports = (self.GUI_PORT, self.API_PORT) if version_tuple(self._version) >= (1, 74) else (self.API_PORT,)
        for port in ports:
            if not _port_free(port):
                return f"本地端口 {port} 被占用；请停止其他服务后重试，不会接管外部实例。"
        return ""

    def _ready(self) -> bool:
        if not self._rc_pid_matches():
            return False
        try:
            _http(self._base_url, self._rc_user, self._rc_pass)
            return self.running()
        except (OSError, ValueError, urllib.error.URLError):
            return False

    def start(self) -> RuntimeStatus:
        with self._operation:
            if self.running():
                return self.status()
            self._status("starting", "正在启动 GUI 并验证本实例服务")
            try:
                error = self._preflight()
                if error:
                    return self._status("failed", error)
                self._rc_url = f"http://{self.HOST}:{self.API_PORT}/"
                modern = version_tuple(self._version) >= (1, 74)
                self._base_url = f"http://{self.HOST}:{self.GUI_PORT}/" if modern else self._rc_url
                self._rc_user = "" if self.cfg.gui_no_auth else self.cfg.gui_user
                self._rc_pass = "" if self.cfg.gui_no_auth else self.cfg.gui_pass
                self._secrets = (self.cfg.gui_user, self.cfg.gui_pass)
                env = _child_environment()
                if modern:
                    args = [self.exe, "gui", "--no-open-browser", "--addr", f"{self.HOST}:{self.GUI_PORT}",
                            "--api-addr", f"{self.HOST}:{self.API_PORT}"]
                    if self.cfg.gui_no_auth:
                        args.append("--no-auth")
                    else:
                        env.update(RCLONE_RC_USER=self._rc_user, RCLONE_RC_PASS=self._rc_pass)
                else:
                    args = [self.exe, "rcd", "--rc-web-gui", "--rc-web-gui-no-open-browser",
                            "--rc-addr", f"{self.HOST}:{self.API_PORT}"]
                    if self.cfg.gui_no_auth:
                        args.append("--rc-no-auth")
                    else:
                        env.update(RCLONE_RC_USER=self._rc_user, RCLONE_RC_PASS=self._rc_pass)
                gui_cache = cache_dir() / "gui"
                gui_cache.mkdir(parents=True, exist_ok=True)
                args += self._config_args() + ["--cache-dir", str(gui_cache)]
                self._open_url = (self._base_url + "login?" + urllib.parse.urlencode({"url": self._rc_url})
                                  if modern else self._base_url + "#/login?" + urllib.parse.urlencode({"url": self._rc_url}))
                if self.cancel.is_set():
                    return self._status("failed", "启动已取消；未创建 GUI 进程。")
                self._spawn(args, env)
                return self._wait_ready()
            except (OSError, ConfigError, ValueError) as exc:
                message = str(exc) if isinstance(exc, ConfigError) else f"GUI 启动失败（{type(exc).__name__}，系统错误 {getattr(exc, 'winerror', None) or getattr(exc, 'errno', None)}）；请检查程序和数据目录。"
                return self._abort_start(message) if self.proc is not None else self._status("failed", message)

    def url(self) -> str:
        return self._open_url if self.status().state == "ready" and self.running() else ""


class MountProcess(BaseProcess):
    def __init__(self, cfg: AppConfig, mount: MountConfig, cancel: threading.Event):
        super().__init__(cfg, f"mount-{mount.id}", cancel)
        self.mount = copy.deepcopy(mount)
        self._spawned = False
        self._probe_thread: Optional[threading.Thread] = None
        self._probe_result = False
        self._probe_time = 0.0
        self._placeholder_removed = False
        self._placeholder_identity: Optional[tuple[int, int]] = None

    def _root(self) -> str:
        target = self.mount.mount_point
        return target + "\\" if re.fullmatch(r"[A-Za-z]:", target) else target

    def _present(self) -> bool:
        if os.name != "nt":
            return os.path.ismount(self._root())
        import ctypes
        from ctypes import wintypes
        kernel = ctypes.WinDLL("kernel32", use_last_error=True)
        root = self._root()
        if re.fullmatch(r"[A-Za-z]:\\", root):
            kernel.GetLogicalDrives.restype = wintypes.DWORD
            if kernel.GetLogicalDrives() & (1 << (ord(root[0].upper()) - ord("A"))):
                return True
            query = kernel.QueryDosDeviceW
            query.argtypes = [wintypes.LPCWSTR, wintypes.LPWSTR, wintypes.DWORD]
            query.restype = wintypes.DWORD
            destination = ctypes.create_unicode_buffer(32768)
            return bool(query(root[:2], destination, len(destination)))
        kernel.GetFileAttributesW.argtypes = [wintypes.LPCWSTR]
        kernel.GetFileAttributesW.restype = wintypes.DWORD
        attributes = kernel.GetFileAttributesW(root)
        return attributes != 0xFFFFFFFF and bool(attributes & 0x400)

    def _volume_ready(self) -> bool:
        if not self._present():
            return False
        # Network providers need not expose local-volume metadata. Opening the
        # root directory proves that applications can actually access the mount.
        # This runs only on the bounded-wait probe thread, never the UI thread.
        with os.scandir(self._root()) as entries:
            next(entries, None)
        return True

    def _probe(self) -> None:
        try:
            ready = self._volume_ready()
        except OSError:
            ready = False
        with self._lock:
            self._probe_result = ready
            self._probe_time = time.monotonic()

    def _ready(self) -> bool:
        if not self._rc_pid_matches():
            return False
        with self._lock:
            if self._probe_thread is None or not self._probe_thread.is_alive():
                if self._probe_result and time.monotonic() - self._probe_time < 1:
                    return True
                self._probe_thread = threading.Thread(target=self._probe, daemon=True,
                                                      name=f"rclone-mount-probe-{self.mount.id}")
                self._probe_thread.start()
        return False

    def owned(self) -> bool:
        return self.running() or self._placeholder_removed or (self._spawned and self._present())

    def _gone(self) -> bool:
        gone = not self._spawned or not self._present()
        if gone:
            self._spawned = False
            self._restore_placeholder()
        return gone

    def _restore_placeholder(self) -> None:
        if not self._placeholder_removed:
            return
        path = Path(self.mount.mount_point)
        try:
            path.mkdir()
        except FileExistsError:
            info = path.lstat()
            if not path.is_dir() or info.st_file_attributes & 0x400:
                raise ConfigError("挂载已卸载，但原空目录路径被其他对象占用；请修复后重试停止。") from None
            with os.scandir(path) as entries:
                if next(entries, None) is not None:
                    raise ConfigError("挂载已卸载，但空目录路径现含文件；不会修改这些文件，请处理后重试停止。")
        except OSError:
            raise ConfigError("挂载已卸载，但恢复原空目录失败；请检查父目录权限并重试停止。") from None
        self._placeholder_removed = False
        self._placeholder_identity = None

    def _remove_placeholder(self) -> None:
        if self._placeholder_identity is None:
            return
        path = Path(self.mount.mount_point)
        info = path.lstat()
        if (info.st_dev, info.st_ino) != self._placeholder_identity or info.st_file_attributes & 0x400:
            raise ConfigError("挂载点在启动前被外部替换；未删除任何对象，请刷新后重试。")
        # rmdir is deliberately non-recursive: a concurrent new file makes it fail.
        path.rmdir()
        self._placeholder_removed = True

    def _mount_args(self) -> list[str]:
        mount = self.mount
        vfs_cache = cache_dir() / "mounts" / mount.id
        vfs_cache.mkdir(parents=True, exist_ok=True)
        args = [self.exe, "mount", mount.remote, mount.mount_point,
                "--vfs-cache-mode", mount.vfs_cache_mode, "--cache-dir", str(vfs_cache),
                "--rc", "--rc-addr", self._rc_url.removeprefix("http://").rstrip("/")]
        if mount.network_mode:
            args.append("--network-mode")
        if mount.read_only:
            args.append("--read-only")
        if mount.volname:
            args += ["--volname", mount.volname]
        elif mount.network_mode:
            args += ["--volname", f"\\\\rclone-tray\\{mount.id}"]
        return args + self._config_args()

    def start(self) -> RuntimeStatus:
        with self._operation:
            if self.running():
                return self.status()
            if self._placeholder_removed or (self._spawned and self._present()):
                return self._status("failed", "上次挂载或空目录恢复尚未完成；请先重试停止。")
            self._status("starting", "正在启动并验证实际挂载")
            try:
                self.mount.validate()
                error = self._preflight()
                if error:
                    return self._status("failed", error)
                if os.name == "nt" and not winfsp_installed():
                    return self._status("failed", "未找到 WinFsp 运行库；请安装匹配架构的 WinFsp 后重新检测。")
                mount = self.mount
                drive = bool(re.fullmatch(r"[A-Za-z]:", mount.mount_point))
                if os.name == "nt":
                    if not drive and not Path(mount.mount_point).is_absolute():
                        return self._status("failed", "挂载点必须是明确盘符（如 X:）或绝对目录路径；不支持自动盘符。")
                    if (mount.network_mode or mount.volname.startswith("\\\\")) and not drive:
                        return self._status("failed", "Windows 网络模式只能挂载到明确盘符；请修改挂载点。")
                    if self._present() or (drive and os.path.lexists(self._root())):
                        return self._status("failed", "挂载点已被占用；请选择未使用盘符或普通空目录。")
                    self._placeholder_identity = None
                    if not drive and os.path.lexists(mount.mount_point):
                        path = Path(mount.mount_point)
                        info = path.lstat()
                        if not path.is_dir() or info.st_file_attributes & 0x400:
                            return self._status("failed", "目录挂载点不能是文件、符号链接或重解析点；请选择普通空目录。")
                        with os.scandir(path) as entries:
                            if next(entries, None) is not None:
                                return self._status("failed", "目录挂载点必须为空；不会删除其中的文件。")
                        self._placeholder_identity = (info.st_dev, info.st_ino)
                    if not drive and not Path(mount.mount_point).parent.is_dir():
                        return self._status("failed", "挂载点父目录不存在；请先创建父目录。")
                self._rc_url = f"http://127.0.0.1:{_available_port()}/"
                self._rc_user, self._rc_pass = "rclone_tray", secrets.token_urlsafe(32)
                self._secrets = (self.cfg.gui_user, self.cfg.gui_pass, self._rc_user, self._rc_pass)
                env = _child_environment()
                env.update(RCLONE_RC_USER=self._rc_user, RCLONE_RC_PASS=self._rc_pass,
                           RCLONE_RC_NO_AUTH="false")
                args = self._mount_args()
                if self.cancel.is_set():
                    return self._status("failed", "启动已取消；未创建挂载进程。")
                self._probe_result = False
                self._probe_time = 0.0
                self._remove_placeholder()
                if self.cancel.is_set():
                    return self._abort_start("启动已取消；未创建挂载进程。")
                self._spawn(args, env)
                self._spawned = True
                return self._wait_ready()
            except (OSError, ConfigError, ValueError) as exc:
                message = str(exc) if isinstance(exc, ConfigError) else f"挂载启动失败（{type(exc).__name__}，系统错误 {getattr(exc, 'winerror', None) or getattr(exc, 'errno', None)}）；请检查挂载点、程序和数据目录。"
                return self._abort_start(message) if self.proc is not None or self._placeholder_removed else self._status("failed", message)


class ProcessManager:
    """Reconfigure metadata in place; never discard live process ownership."""

    def __init__(self, cfg: AppConfig):
        cfg.validate()
        self.cfg = copy.deepcopy(cfg)
        self.cancel = threading.Event()
        self._lock = threading.RLock()
        self.gui = GuiService(self.cfg, self.cancel)
        self.mounts = {mount.id: MountProcess(self.cfg, mount, self.cancel) for mount in self.cfg.mounts}

    @staticmethod
    def _mount_connection(mount: MountConfig) -> tuple:
        return (mount.remote, mount.mount_point, mount.vfs_cache_mode,
                mount.network_mode, mount.read_only, mount.volname)

    def update_config(self, cfg: AppConfig) -> None:
        cfg.validate()
        candidate = copy.deepcopy(cfg)
        proposed = {mount.id: mount for mount in candidate.mounts}
        with self._lock:
            environment_changed = (candidate.rclone_path, candidate.rclone_conf) != (self.cfg.rclone_path, self.cfg.rclone_conf)
            gui_auth_changed = (candidate.gui_no_auth, candidate.gui_user, candidate.gui_pass) != (
                self.cfg.gui_no_auth, self.cfg.gui_user, self.cfg.gui_pass)
            if self.gui.owned() and (environment_changed or gui_auth_changed):
                raise ValueError("GUI 正在运行；请先停止 GUI 再修改程序路径、rclone 配置或认证。")
            for mid, process in self.mounts.items():
                if process.owned() and (mid not in proposed or environment_changed or
                        self._mount_connection(process.mount) != self._mount_connection(proposed[mid])):
                    raise ValueError("挂载仍在运行或尚未卸载；请先停止，再修改连接参数或删除。")
            # All rejecting checks completed before any mutation; every unchanged ID retains its object/Popen.
            self.cfg = candidate
            if not self.gui.owned():
                self.gui.cfg = copy.deepcopy(candidate)
                self.gui.exe = candidate.rclone_path
            updated = {}
            for mount in candidate.mounts:
                process = self.mounts.get(mount.id)
                if process is None:
                    process = MountProcess(candidate, mount, self.cancel)
                else:
                    if not process.owned():
                        process.cfg = copy.deepcopy(candidate)
                        process.exe = candidate.rclone_path
                    process.mount = copy.deepcopy(mount)
                updated[mount.id] = process
            self.mounts = updated

    def statuses(self) -> tuple[RuntimeStatus, dict[str, RuntimeStatus]]:
        with self._lock:
            return self.gui.status(), {mid: process.status() for mid, process in self.mounts.items()}

    def start_gui(self) -> RuntimeStatus:
        return self.gui.start()

    def stop_gui(self) -> RuntimeStatus:
        return self.gui.stop()

    def gui_url(self) -> str:
        return self.gui.url()

    def start_mount(self, mid: str) -> RuntimeStatus:
        with self._lock:
            process = self.mounts.get(mid)
        return process.start() if process is not None else RuntimeStatus("failed", "挂载配置已不存在；请刷新列表。")

    def stop_mount(self, mid: str) -> RuntimeStatus:
        with self._lock:
            process = self.mounts.get(mid)
        return process.stop() if process is not None else RuntimeStatus("failed", "挂载配置已不存在；请刷新列表。")

    def start_all_mounts(self, auto_only: bool = False) -> dict[str, RuntimeStatus]:
        with self._lock:
            processes = tuple(self.mounts.items())
        return {mid: process.start() for mid, process in processes if not auto_only or process.mount.auto_mount}

    def stop_all(self) -> dict[str, RuntimeStatus]:
        results = {"gui": self.stop_gui()}
        with self._lock:
            processes = tuple(self.mounts.items())
        for mid, process in processes:
            results[mid] = process.stop()
        return results
